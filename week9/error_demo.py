"""
Week 9 — before/after transcript for ONE failing tool call on our own server.

The failing call is replayed identically in both phases:
    policy_docs__get_policy_clause({"clause_id": "4.2"})
("4.2" is how a customer letter cites the flood clause; the real id is "4.2b".)

It is injected as the assistant's first turn and executed against the LIVE
server, so the only thing that differs between phases is the server's own
docstring (the tool description from tools/list) and its error text. The
model then handles that result however it chooses.

Usage:
    python3 week9/error_demo.py before   # with the original docstring / "Error 3"
    python3 week9/error_demo.py after    # after rewriting the server
    python3 week9/error_demo.py report   # writes week9/error_before_after.md
"""

import json
import pathlib
import sys

WEEK9 = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(WEEK9.parent))

from week9.agent import MCPHost, run

CONFIG  = WEEK9 / "error_demo_config.json"
QUERY   = ("A customer's letter says their claim was refused under "
           "'clause 4.2' of the policy. Quote what that clause actually says.")
SEED    = [("policy_docs__get_policy_clause", {"clause_id": "4.2"})]
REPEATS = 3
OUT     = WEEK9 / "evidence"
MD      = WEEK9 / "error_before_after.md"


def capture(phase: str):
    host = MCPHost(CONFIG).connect()
    try:
        tool = host.tools["policy_docs__get_policy_clause"]
        description, schema = tool["description"], tool["inputSchema"]
    finally:
        host.close()
    runs = []
    for i in range(REPEATS):
        r = run(QUERY, CONFIG, seed_tool_calls=SEED)
        r["repeat"] = i + 1
        runs.append(r)
        calls = [s for s in r["trace"] if s["type"] == "tool_call"]
        print(f"[{phase}] repeat {i + 1}: {len(calls)} tool calls, "
              f"{r['llm_calls']} model calls, {r['total_tokens']} tokens")
        for s in calls:
            print(f"    {s['tool']}({json.dumps(s['args'])}) "
                  f"{'ERROR ' if s['is_error'] else ''}-> {s['result'][:120]}")
        print(f"    answer: {(r['answer'] or '')[:200]}")
    OUT.mkdir(exist_ok=True)
    (OUT / f"error_{phase}.json").write_text(json.dumps(
        {"phase": phase, "tool_description": description, "input_schema": schema,
         "query": QUERY, "seeded_call": SEED, "runs": runs}, indent=2))


def _summary(run_: dict) -> dict:
    calls = [s for s in run_["trace"] if s["type"] == "tool_call"]
    after_seed = calls[1:]
    got_clause = any(s["tool"] == "get_policy_clause" and not s["is_error"] for s in calls)
    return {"tool_calls_after_error": len(after_seed),
            "recovered": got_clause,
            "path": " > ".join(f"{s['tool']}({json.dumps(s['args'])})" for s in calls)}


def report():
    B = json.loads((OUT / "error_before.json").read_text())
    A = json.loads((OUT / "error_after.json").read_text())
    md = ["# error_before_after.md — same failing call, old docstring/error vs new\n",
          "**Server:** our own `policy-docs` MCP server (`week9/servers/policy_docs_server.py`).  ",
          "**Tool:** `get_policy_clause`.  ",
          f"**Query:** {QUERY}  ",
          "**Failing call (identical in both phases):** "
          "`get_policy_clause({\"clause_id\": \"4.2\"})`. The real id is `4.2b`.  ",
          "Method: the call is injected as the model's first turn and executed against the "
          "live server, so the only variable is the server's docstring and error text. Model: "
          f"`{B['runs'][0]['model']}`, temperature 0, {REPEATS} repeats per phase. "
          "Generated by `python3 week9/error_demo.py report` from `evidence/error_before.json` "
          "and `evidence/error_after.json`.\n"]

    for title, P in (("BEFORE", B), ("AFTER", A)):
        md.append(f"## {title}\n")
        md.append("Tool description the model saw (from `tools/list`, i.e. the docstring):\n")
        md.append("```text\n" + P["tool_description"] + "\n```\n")
        r0 = P["runs"][0]
        seed_res = next(s for s in r0["trace"] if s["type"] == "tool_call")
        md.append("Server response to the failing call (`isError: "
                  f"{str(seed_res['is_error']).lower()}`):\n")
        md.append("```text\n" + seed_res["result"] + "\n```\n")
        md.append("| Repeat | Recovered the clause? | Tool calls after the error | "
                  "Model calls | Tokens | Path |")
        md.append("|---|---|---|---|---|---|")
        for r in P["runs"]:
            s = _summary(r)
            md.append(f"| {r['repeat']} | {'yes' if s['recovered'] else 'no'} | "
                      f"{s['tool_calls_after_error']} | {r['llm_calls']} | "
                      f"{r['total_tokens']} | `{s['path']}` |")
        md.append("")
        md.append(f"Transcript (repeat 1):\n")
        lines = [f"USER: {QUERY}"]
        for s in r0["trace"]:
            if s["type"] == "seeded_turn":
                continue
            lines.append(f"MODEL -> tool_call {s['tool']}({json.dumps(s['args'])})")
            lines.append(f"SERVER -> {'[isError] ' if s['is_error'] else ''}{s['result'][:400]}")
        lines.append(f"MODEL -> final answer: {r0['answer']}")
        md.append("```text\n" + "\n".join(lines) + "\n```\n")

    rb = sum(_summary(r)["recovered"] for r in B["runs"])
    ra = sum(_summary(r)["recovered"] for r in A["runs"])
    cb = sum(_summary(r)["tool_calls_after_error"] for r in B["runs"]) / REPEATS
    ca = sum(_summary(r)["tool_calls_after_error"] for r in A["runs"]) / REPEATS
    mb = sum(r["llm_calls"] for r in B["runs"]) / REPEATS
    ma = sum(r["llm_calls"] for r in A["runs"]) / REPEATS

    def grounded(run_):
        """Was 4.2b present in some tool result BEFORE the model fetched it?"""
        calls = [s for s in run_["trace"] if s["type"] == "tool_call"]
        for i, s in enumerate(calls):
            if s["tool"] == "get_policy_clause" and not s["is_error"]:
                return any("4.2b" in c["result"] for c in calls[:i])
        return False

    gb = sum(grounded(r) for r in B["runs"])
    ga = sum(grounded(r) for r in A["runs"])
    md.append("## Result\n")
    md.append(f"- Fetched the real clause after the failing call: **{rb}/{REPEATS} before "
              f"→ {ra}/{REPEATS} after**.")
    md.append(f"- …and the id `4.2b` appeared in a tool result before the model used it "
              f"(a grounded recovery, not a guess): **{gb}/{REPEATS} before → {ga}/{REPEATS} after**.")
    md.append(f"- Tool calls needed after the error: **{cb:.2f} → {ca:.2f}**; "
              f"model calls per run: **{mb:.2f} → {ma:.2f}**.")
    tb = sum(r["total_tokens"] for r in B["runs"]) / REPEATS
    ta = sum(r["total_tokens"] for r in A["runs"]) / REPEATS
    md.append(f"- Mean tokens per run: {tb:.0f} before → {ta:.0f} after "
              f"({ta - tb:+.0f}). This includes the longer tool description, which is sent on "
              f"every model call.")
    md.append("")
    MD.write_text("\n".join(md))
    print(f"wrote {MD}")


if __name__ == "__main__":
    phase = sys.argv[1] if len(sys.argv) > 1 else ""
    if phase in ("before", "after"):
        capture(phase)
    elif phase == "report":
        report()
    else:
        sys.exit("usage: error_demo.py before|after|report")
